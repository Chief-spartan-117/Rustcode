/// Register editor key bindings. Call once at startup.
pub fn init(cx: &mut App) {
    cx.on_action(|_: &Quit, cx| cx.quit());
    cx.bind_keys([KeyBinding::new("secondary-q", Quit, None)]);
    let ctx = Some(EDITOR_CONTEXT);
    let wb = Some(WORKBENCH_CONTEXT);
    cx.bind_keys([
        KeyBinding::new("secondary-b", ToggleSidebar, wb),
        KeyBinding::new("secondary-k secondary-o", OpenFolder, wb),
        KeyBinding::new("secondary-shift-e", FocusExplorer, wb),
        KeyBinding::new("secondary-shift-f", OpenSearch, wb),
        KeyBinding::new("ctrl-shift-g", OpenSourceControl, wb),
        KeyBinding::new("secondary-j", TogglePanel, wb),
        KeyBinding::new("secondary-shift-v", ToggleMarkdownPreview, wb),
        KeyBinding::new("alt-z", ToggleWordWrap, wb),
        KeyBinding::new("secondary-k v", OpenMarkdownPreviewPanel, wb),
        KeyBinding::new("secondary-alt-v", ToggleMarkdownFullPreview, wb),
        KeyBinding::new("secondary-\\", SplitRight, wb),
        KeyBinding::new("secondary-k secondary-\\", SplitDown, wb),
        KeyBinding::new("secondary-k secondary-w", CloseGroup, wb),
        KeyBinding::new("secondary-k secondary-right", FocusNextGroup, wb),
        KeyBinding::new("secondary-k secondary-left", FocusPreviousGroup, wb),
        KeyBinding::new("secondary-k secondary-shift-right", MoveTabToNextGroup, wb),
        KeyBinding::new("secondary-n", NewFile, wb),
        KeyBinding::new("secondary-o", OpenFile, wb),
        KeyBinding::new("secondary-p", QuickOpen, wb),
        KeyBinding::new("ctrl-g", GoToLine, wb),
        KeyBinding::new("secondary-shift-s", SaveAs, wb),
        KeyBinding::new("secondary-w", CloseTab, wb),
        KeyBinding::new("ctrl-tab", NextTab, wb),
        KeyBinding::new("ctrl-shift-tab", PreviousTab, wb),
        KeyBinding::new("secondary-shift-]", NextTab, wb),
        KeyBinding::new("secondary-shift-[", PreviousTab, wb),
        KeyBinding::new("secondary-shift-p", OpenCommandPalette, wb),
        KeyBinding::new("secondary-,", OpenSettingsPage, wb),
        KeyBinding::new("secondary-k secondary-s", OpenShortcutsPage, wb),
        KeyBinding::new("secondary-k secondary-t", OpenThemePicker, wb),
        KeyBinding::new("ctrl-`", ToggleTerminal, wb),
        KeyBinding::new("secondary-shift-m", ShowProblems, wb),
        KeyBinding::new("secondary-alt-s", SaveAll, wb),
        KeyBinding::new("secondary-1", FocusEditor, wb),
    ]);
    cx.bind_keys([
        KeyBinding::new("left", MoveLeft, ctx),
        KeyBinding::new("right", MoveRight, ctx),
        KeyBinding::new("up", MoveUp, ctx),
        KeyBinding::new("down", MoveDown, ctx),
        KeyBinding::new("shift-left", SelectLeft, ctx),
        KeyBinding::new("shift-right", SelectRight, ctx),
        KeyBinding::new("shift-up", SelectUp, ctx),
        KeyBinding::new("shift-down", SelectDown, ctx),
        KeyBinding::new("home", MoveToLineStart, ctx),
        KeyBinding::new("end", MoveToLineEnd, ctx),
        KeyBinding::new("shift-home", SelectToLineStart, ctx),
        KeyBinding::new("shift-end", SelectToLineEnd, ctx),
        KeyBinding::new("secondary-a", SelectAll, ctx),
        KeyBinding::new("backspace", Backspace, ctx),
        KeyBinding::new("secondary-/", ToggleLineComment, ctx),
        KeyBinding::new("shift-alt-a", ToggleBlockComment, ctx),
        KeyBinding::new("delete", Delete, ctx),
        KeyBinding::new("shift-backspace", Backspace, ctx),
        KeyBinding::new("shift-delete", Delete, ctx),
        KeyBinding::new("alt-backspace", DeleteWordLeft, ctx),
        KeyBinding::new("alt-delete", DeleteWordRight, ctx),
        KeyBinding::new("ctrl-backspace", DeleteWordLeft, ctx),
        KeyBinding::new("ctrl-delete", DeleteWordRight, ctx),
        KeyBinding::new("enter", Newline, ctx),
        KeyBinding::new("tab", Tab, ctx),
        KeyBinding::new("shift-tab", BackTab, ctx),
        KeyBinding::new("secondary-z", Undo, ctx),
        KeyBinding::new("secondary-shift-z", Redo, ctx),
        KeyBinding::new("secondary-c", Copy, ctx),
        KeyBinding::new("secondary-x", Cut, ctx),
        KeyBinding::new("secondary-v", Paste, ctx),
        KeyBinding::new("secondary-s", Save, ctx),
        KeyBinding::new("secondary-alt-up", AddCursorAbove, ctx),
        KeyBinding::new("secondary-alt-down", AddCursorBelow, ctx),
        KeyBinding::new("secondary-f", OpenFind, ctx),
        KeyBinding::new("secondary-alt-f", OpenReplace, ctx),
        KeyBinding::new("f12", GoToDefinition, ctx),
        KeyBinding::new("f5", DebugStart, ctx),
        KeyBinding::new("shift-f5", DebugStop, ctx),
        KeyBinding::new("secondary-shift-f5", DebugRestart, ctx),
        KeyBinding::new("f10", DebugStepOver, ctx),
        KeyBinding::new("f11", DebugStepInto, ctx),
        KeyBinding::new("shift-f11", DebugStepOut, ctx),
        KeyBinding::new("f6", DebugPause, ctx),
        KeyBinding::new("f9", ToggleBreakpoint, ctx),
        KeyBinding::new("secondary-f12", GoToImplementation, ctx),
        KeyBinding::new("shift-alt-h", ShowIncomingCalls, ctx),
        KeyBinding::new("secondary-alt-[", FoldRegion, ctx),
        KeyBinding::new("secondary-shift-\\", GoToBracket, ctx),
        KeyBinding::new("secondary-alt-]", UnfoldRegion, ctx),
        KeyBinding::new("secondary-k secondary-l", ToggleFold, ctx),
        KeyBinding::new("secondary-k secondary-0", FoldAll, ctx),
        KeyBinding::new("secondary-k secondary-j", UnfoldAll, ctx),
        KeyBinding::new("f2", RenameSymbol, ctx),
        KeyBinding::new("shift-alt-f", FormatDocument, ctx),
        KeyBinding::new("secondary-k secondary-f", FormatSelection, ctx),
        KeyBinding::new("shift-f12", FindReferences, ctx),
        KeyBinding::new("secondary-.", QuickFix, ctx),
        KeyBinding::new("ctrl-shift-space", ParameterHints, ctx),
        // VS Code's own keys: with the command key on a Mac, with alt elsewhere.
        KeyBinding::new(if cfg!(target_os = "macos") { "ctrl-shift-secondary-right" } else { "shift-alt-right" }, ExpandSelection, ctx),
        KeyBinding::new(if cfg!(target_os = "macos") { "ctrl-shift-secondary-left" } else { "shift-alt-left" }, ShrinkSelection, ctx),
        KeyBinding::new("secondary-shift-o", GoToSymbol, wb),
        KeyBinding::new("secondary-t", GoToWorkspaceSymbol, wb),
        KeyBinding::new("ctrl-space", TriggerSuggest, ctx),
        KeyBinding::new("secondary-k secondary-i", ShowHover, ctx),
        KeyBinding::new("f3", FindNext, ctx),
        KeyBinding::new("shift-f3", FindPrevious, ctx),
        KeyBinding::new("secondary-shift-g", FindPrevious, ctx),
        KeyBinding::new("shift-enter", FindPrevious, ctx),
        KeyBinding::new("escape", CloseFind, ctx),
        KeyBinding::new("secondary-alt-c", ToggleCaseSensitive, ctx),
        KeyBinding::new("secondary-alt-w", ToggleWholeWord, ctx),
        KeyBinding::new("secondary-alt-r", ToggleRegex, ctx),
        KeyBinding::new("secondary-alt-enter", ReplaceAll, ctx),
    ]);
    if cfg!(target_os = "macos") {
        cx.bind_keys([
            KeyBinding::new("cmd-left", MoveToLineStart, ctx),
            KeyBinding::new("cmd-right", MoveToLineEnd, ctx),
            KeyBinding::new("cmd-shift-left", SelectToLineStart, ctx),
            KeyBinding::new("cmd-shift-right", SelectToLineEnd, ctx),
            KeyBinding::new("cmd-up", MoveToDocumentStart, ctx),
            KeyBinding::new("cmd-down", MoveToDocumentEnd, ctx),
            KeyBinding::new("cmd-shift-up", SelectToDocumentStart, ctx),
            KeyBinding::new("cmd-shift-down", SelectToDocumentEnd, ctx),
            KeyBinding::new("alt-left", MoveWordLeft, ctx),
            KeyBinding::new("alt-right", MoveWordRight, ctx),
            KeyBinding::new("alt-shift-left", SelectWordLeft, ctx),
            KeyBinding::new("alt-shift-right", SelectWordRight, ctx),
            KeyBinding::new("cmd-backspace", DeleteToLineStart, ctx),
            KeyBinding::new("cmd-delete", DeleteToLineEnd, ctx),
        ]);
    } else {
        cx.bind_keys([
            KeyBinding::new("ctrl-home", MoveToDocumentStart, ctx),
            KeyBinding::new("ctrl-end", MoveToDocumentEnd, ctx),
            KeyBinding::new("ctrl-shift-home", SelectToDocumentStart, ctx),
            KeyBinding::new("ctrl-shift-end", SelectToDocumentEnd, ctx),
            KeyBinding::new("ctrl-left", MoveWordLeft, ctx),
            KeyBinding::new("ctrl-right", MoveWordRight, ctx),
            KeyBinding::new("ctrl-shift-left", SelectWordLeft, ctx),
            KeyBinding::new("ctrl-shift-right", SelectWordRight, ctx),
            KeyBinding::new("alt-up", AddCursorAbove, ctx),
            KeyBinding::new("alt-down", AddCursorBelow, ctx),
        ]);
    }
    let explorer = Some(EXPLORER_CONTEXT);
    cx.bind_keys([
        KeyBinding::new("up", ExplorerUp, explorer),
        KeyBinding::new("down", ExplorerDown, explorer),
        KeyBinding::new("left", ExplorerLeft, explorer),
        KeyBinding::new("right", ExplorerRight, explorer),
        KeyBinding::new("enter", ExplorerAccept, explorer),
        KeyBinding::new("f2", ExplorerRename, explorer),
        KeyBinding::new("delete", ExplorerDelete, explorer),
        KeyBinding::new("backspace", ExplorerDelete, explorer),
        KeyBinding::new("escape", ExplorerBack, explorer),
        KeyBinding::new("secondary-c", ExplorerCopy, explorer),
        KeyBinding::new("secondary-x", ExplorerCut, explorer),
        KeyBinding::new("secondary-v", ExplorerPaste, explorer),
        KeyBinding::new("shift-up", ExplorerExtendUp, explorer),
        KeyBinding::new("shift-down", ExplorerExtendDown, explorer),
    ]);
    // Cmd+G finds next on macOS; elsewhere Ctrl+G is Go to Line and F3 finds next.
    if cfg!(target_os = "macos") {
        cx.bind_keys([KeyBinding::new("secondary-g", FindNext, ctx)]);
    }
    let terminal = Some(TERMINAL_CONTEXT);
    cx.bind_keys([
        KeyBinding::new("secondary-v", TerminalPaste, terminal),
        KeyBinding::new("secondary-c", TerminalCopy, terminal),
    ]);
    // Keyboard navigation of the in-window menu, active only while one is open.
    let menu = Some(MENU_CONTEXT);
    cx.bind_keys([
        KeyBinding::new("up", MenuUp, menu),
        KeyBinding::new("down", MenuDown, menu),
        KeyBinding::new("left", MenuLeft, menu),
        KeyBinding::new("right", MenuRight, menu),
        KeyBinding::new("enter", MenuAccept, menu),
        KeyBinding::new("escape", MenuBack, menu),
    ]);
    if !cfg!(target_os = "macos") {
        // Alt+letter opens a menu, like Windows and VS Code. macOS uses Alt for typing.
        for context in [Some(WORKBENCH_CONTEXT), menu] {
            cx.bind_keys([
                KeyBinding::new("alt-f", OpenFileMenu, context),
                KeyBinding::new("alt-e", OpenEditMenu, context),
                KeyBinding::new("alt-s", OpenSelectionMenu, context),
                KeyBinding::new("alt-v", OpenViewMenu, context),
                KeyBinding::new("alt-h", OpenHelpMenu, context),
            ]);
        }
    }
    // After the key bindings, so the system menu shows each item's shortcut.
    if cfg!(target_os = "macos") {
        cx.set_menus(crate::menu::native_menus());
    }
}
